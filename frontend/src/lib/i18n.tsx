const I18nContext = createContext<{ lang: Lang; setLang: (l: Lang) => void; t: (key: string, vars?: Record<string, string | number>) => string }>({
  lang: "tr",
  setLang: () => {},
  t: (key) => key,
});

const STORAGE_KEY = "subly.lang";
const KNOWN_LANGS: Lang[] = ["tr", "en", "de", "es", "fr"];

export function readLang(): Lang {
  if (typeof window === "undefined") return "tr";
  const saved = window.localStorage.getItem(STORAGE_KEY) as Lang | null;
  if (saved && KNOWN_LANGS.includes(saved)) return saved;
  const browser = (window.navigator.language || "").slice(0, 2).toLowerCase();
  const match = KNOWN_LANGS.find((code) => code === browser);
  return match ?? "en";
}

export function interpolate(template: string, vars?: Record<string, string | number>): string {
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (_m, k) => (vars[k] !== undefined ? String(vars[k]) : `{${k}}`));
}

// Pure fallback-chain resolver, factored out of I18nProvider's t() so it's
// unit-testable without rendering React: active dict -> English dict -> the
// raw key itself (never crashes, never throws on a missing key).
export function translate(dict: Dict, fallbackDict: Dict, key: string, vars?: Record<string, string | number>): string {
  const raw = dict[key] ?? fallbackDict[key] ?? key;
  return interpolate(raw, vars);
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(() => readLang());

  useEffect(() => {
    if (typeof document !== "undefined") {
      document.documentElement.lang = lang;
    }
    setFormatLocale(lang);
  }, [lang]);

  const setLang = (next: Lang) => {
    setLangState(next);
    try { window.localStorage.setItem(STORAGE_KEY, next); } catch { /* ignore */ }
  };

  const value = useMemo(() => ({
    lang,
    setLang,
    t: (key: string, vars?: Record<string, string | number>) => translate(STRINGS[lang] ?? STRINGS.en, STRINGS.en, key, vars),
  }), [lang]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useT() {
  return useContext(I18nContext);
}
